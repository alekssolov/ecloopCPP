// ----------------------------------------------------------------------------
// Base58
// ----------------------------------------------------------------------------

// Декодирует строку Base58 в двоичный вид.
//
//   bin      -- буфер приёмника
//   binszp   -- на входе размер буфера, на выходе реальное число байт
//   b58      -- строка
//   b58sz    -- её длина; 0 означает "строка завершена нулём"
//
// Возвращает false, если встретился символ вне алфавита или результат не
// помещается в буфер. Для адреса Bitcoin нужен буфер в 25 байт.
//
// Учтите, что *binszp -- параметр в обе стороны: перед каждым вызовом его
// надо заново выставлять в размер буфера, иначе второй вызов увидит длину,
// оставшуюся от первого.
bool b58tobin(void* bin, std::size_t* binszp, const char* b58, std::size_t b58sz);

// Кодирует двоичные данные в Base58 и завершает строку нулём.
//
// Буфер должен вмещать binsz * 138 / 100 + 2 символа: множитель -- это
// log(256)/log(58) с запасом, плюс байт под ноль. Для 25 байт адреса
// достаточно 40; ведущие нулевые байты дают по одному символу '1' каждый и в
// эту оценку уже входят.
bool b58enc(char* b58, const void* data, std::size_t binsz);

// ----------------------------------------------------------------------------
// Префиксы и сложность
// ----------------------------------------------------------------------------

// Добавляет префикс адреса в набор искомых.
//
// Префикс задаётся так, как должен читаться адрес, вместе с ведущей единицей:
// "1Bit", а не "Bit". Допустимы символы алфавита Base58, то есть без 0, O, I
// и l. Вызовов может быть несколько, диапазоны накапливаются и пересекающиеся
// сливаются.
//
// Возвращает false, если префикс отвергнут. При внутренней ошибке печатает
// сообщение и завершает процесс -- поведение унаследовано, имейте в виду при
// вызове из долго работающего кода.
bool add_prefix(const char* prefix);

// Сложность нахождения адреса с любым из добавленных префиксов.
//
// Это величина, обратная вероятности: в среднем столько ключей придётся
// перебрать. Полезно знать три вещи о её краях.
//
// Потолок -- 2^160, примерно 1.4615e48. Столько всего существует значений
// hash160, и такой ответ означает, что префикс задал адрес однозначно.
// Достигается с 29 символов: дальше лишние символы уже ничего не сужают,
// потому что четыре байта контрольной суммы префиксом не управляются.
//
// Бесконечность означает, что таких адресов не существует вовсе. Это не
// ошибка и не переполнение: из 58 вариантов 29-го символа достижимыми
// оказываются в среднем девять, остальные не отвечают ни одному hash160.
// Проверяйте на std::isinf, прежде чем печатать или делить.
//
// Ноль возвращается, только если не добавлено ни одного префикса.
double get_difficulty();

// ----------------------------------------------------------------------------
// Только для чтения: диапазоны для движка
// ----------------------------------------------------------------------------
// add_prefix уже построил и слил диапазоны hash160 для расчёта сложности.
// Ниже -- просто копия этих диапазонов, ничего не пересчитывает и не меняет
// PatternSet. Движку (engine_x8.cpp) это нужно для быстрой предварительной
// проверки кандидата перед точной сверкой адреса, той же формы, что и
// btf_maybe() перед btree_search() в поиске по BIN.

struct PrefixRange {
	unsigned char low[20];
	unsigned char high[20];
	
};

// Копия текущего набора диапазонов, в порядке, в котором add_prefix их
// накопил. Пустой vector, если add_prefix ещё не вызывался или ни один вызов
// не завершился успехом. Границы включительно, порядок байт как в теле
// адреса: low[0]/high[0] -- старший байт.
std::vector<PrefixRange> prefix_ranges();

