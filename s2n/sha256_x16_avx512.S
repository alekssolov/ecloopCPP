// ============================================================================
// sha256_x16_avx512.S -- SHA-256 over 16 messages per pass, AVX-512.
//
// Port of minio/sha256-simd (sha256blockAvx512_amd64.s) from Go assembly
// to GAS. The body is 15416 bytes of machine code which the original
// spelled out with LONG/QUAD/WORD/BYTE directives (the Go assembler did
// not know AVX-512 mnemonics at the time). Those bytes are carried over
// verbatim; only 113 mnemonics were translated: prologue, branches, data.
//
// BUILD -- one command, no preprocessor tricks:
//     gcc -c sha256_x16_avx512.S -o sha256_x16_avx512.o
// No -DWINDOWS_ABI, no `tr ';' '\n'`, no -I. needed.
//
// C interface:
//   void sha256_x16_avx512(void *digests, void *scratch, const void *table,
//                          const void *mask, uint64_t mask_len,
//                          const unsigned char *const *inputs);
//
//   digests  512 bytes, u32[8][16], LANE-MAJOR: hash word x 16 messages.
//            Holds the initial state on entry, the result on exit.
//   table    4096 bytes, u32[64][16]: round constant broadcast over lanes.
//   mask     one u64 per 64-byte block, bit set = lane still active.
//   scratch  512 bytes of working memory.
//   inputs   16 message pointers (stride 8 bytes, not 24 as in Go).
//
// DIFFERENCES FROM THE ORIGINAL
//
// 1. Calling convention. Go passed everything on the stack (FP-relative):
//      func sha256X16Avx512(digests, scratch *[512]byte, table *[512]uint64,
//                           mask []uint64, inputs [16][]byte)
//    Here it is an ordinary C function, with separate prologues for SysV
//    and Windows.
//
// 2. Input array stride. In Go `inputs` was an array of slices, 24 bytes
//    each (pointer + len + cap), and the code read N*24(AX). Here it is a
//    plain array of pointers, so N*8(AX). Miss this and the function reads
//    garbage from the second lane onwards.
//
// 3. Table pointer. The original re-read it from the stack inside the loop
//    (MOVQ table+16(FP), DX). There are no stack arguments any more, so it
//    lives in r15 and is copied into rdx at the same places.
//
// 4. Prologue/epilogue. The Go function was frameless (NOSPLIT, $0). Here
//    rbx/rbp/r12-r15 are saved, and under the Windows ABI also rdi, rsi
//    and the low 128 bits of xmm6-xmm15.
//
//    rdi and rsi matter especially: under the Windows ABI they are
//    CALLEE-SAVED, whereas under SysV they are volatile argument
//    registers. The body uses both as scratch (rdi = digests pointer,
//    rsi = block counter). Not saving them corrupts two registers of the
//    caller -- and it shows up far from the cause, because if nothing live
//    happens to sit in rdi/rsi at the call site the call succeeds. Hash
//    correctness tests do not catch this at all: the hashes are right, the
//    caller's memory is not. See tests/t_clobber.c.
//
// The body addresses memory through r12 (scratch), never through rsp, so
// the added frame is safe.
// ============================================================================

